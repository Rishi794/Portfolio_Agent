"""Builds the Markdown trade ticket posted as a GitHub Issue.

The ticket is the *human approval surface*: nothing executes until a collaborator
comments ``/approve`` (optionally with real broker fills, e.g.
``/approve NVDA=25@128.40 RELIANCE.NS=40@2945.50``).
"""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path
from typing import Any

import pandas as pd

PILLARS = ("kalman_trend", "fundamentals", "tech_evolution", "gov_policy", "geopolitics", "macro_beta")


def build_issue_body(
    summary: dict[str, Any],
    config,
    output_path: str | Path,
    *,
    lake=None,
    state_dir: str | Path | None = None,
) -> Path:
    top_n = int(config.e("reporting.top_n_display", 25))
    lines: list[str] = []
    mode = summary.get("mode", "daily_eod")
    markets = list(summary.get("markets", {}))
    label = "🌏 V4 Autonomous Signals" if mode != "synthetic_demo" else "🧪 V4 Synthetic Demo (no external data)"
    lines.append(f"# {label} — {summary.get('as_of')}")
    lines.append("")
    lines.append(f"**Run** `{summary.get('run_id')}` · **mode** `{mode}` · **markets** `{', '.join(markets)}`")
    lines.append(
        f"**Window** {summary.get('started_at', '')[:19]}Z → {summary.get('finished_at', '')[:19]}Z · "
        f"**config hash** `{config.fingerprint()}`"
    )
    lines.append("")
    if mode == "synthetic_demo":
        lines.append(
            "> ⚠️ **Synthetic demo run.** The lakehouse was generated by `src/synthetic.py`; no live market, "
            "policy or filing data was fetched. Structure and math are production paths, numbers are not."
        )
        lines.append("")

    for market in markets:
        run = _run_for(summary, market)
        diagnostics = summary["markets"].get(market, {}) or {}
        lines.extend(_market_block(market, run, diagnostics, top_n))
        lines.append("")

    lines.extend(_order_block(summary, top_n))
    lines.extend(_calibration_block(summary, config))
    lines.extend(_approval_block())
    lines.extend(_lakehouse_block(summary))

    path = Path(output_path)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _run_for(summary: dict[str, Any], market: str):
    for run in summary.get("runs", []):
        if getattr(run, "market", None) == market:
            return run
    return None


def _market_block(market: str, run, diagnostics: dict[str, Any], top_n: int) -> list[str]:
    currency = "₹" if market == "INDIA" else "$"
    regime = diagnostics.get("regime", "UNKNOWN")
    lines = [
        f"## {'🇮🇳' if market == 'INDIA' else '🇺🇸'} {market} (`{currency}`)",
        "",
        f"**Regime** `{regime}` · **Mahalanobis turbulence** `{_fmt(diagnostics.get('turbulence_d2'))}` "
        f"(χ²₆ 90th pct = 10.64) · **cash buffer** `{_pct(diagnostics.get('cash_buffer'))}` · "
        f"**universe** {diagnostics.get('universe', 0)} → **eligible** {diagnostics.get('eligible', 0)}",
        "",
    ]
    weights = diagnostics.get("pillar_weights")
    if weights:
        names = diagnostics.get("pillar_names") or list(PILLARS)
        lines.append(
            "**Pillar weights** "
            + " · ".join(f"`{name}`={weight:.3f}" for name, weight in zip(names, weights))
            + f" · weight mode `{diagnostics.get('mode', 'n/a')}` ({diagnostics.get('observations', 0)} IC obs)"
        )
        timestral_mode = diagnostics.get("timestral_mode")
        if timestral_mode:
            lines.append(f"**Timestral 7th pillar** mode `{timestral_mode}`")
        lines.append("")
    lines.append(
        f"**Signal hygiene** raw max |ρ| `{_fmt(diagnostics.get('raw_max_abs_correlation'))}` → "
        f"orthogonalized max |ρ| `{_fmt(diagnostics.get('ortho_max_abs_correlation'))}` · "
        f"‖F F' /N − I‖_F `{_fmt(diagnostics.get('orthogonality_error'))}`"
    )
    lines.append("")
    policy = diagnostics.get("policy", {}) or {}
    geopolitics = diagnostics.get("geopolitics", {}) or {}
    lines.append(
        f"**Event gate** policy τ̂ `{_fmt(policy.get('tau_hat'))}` ({policy.get('events', 0):.0f} events, "
        f"BH-FDR α `{_fmt(policy.get('alpha_fdr'))}`) · geopolitics τ̂ `{_fmt(geopolitics.get('tau_hat'))}` "
        f"({geopolitics.get('events', 0):.0f} events) · backend `{policy.get('backend', 'n/a')}` "
        f"({policy.get('polarity_mode', 'n/a')})"
    )
    lines.append("")

    target = getattr(run, "target_weights", None)
    alpha = getattr(run, "alpha", None)
    if target is not None and not target.empty:
        lines.append(f"| # | Ticker | Target wt | α (ortho) | {currency} level |")
        lines.append("| ---: | :--- | ---: | ---: | ---: |")
        price_series = pd.Series(dtype=float)
        for idx, (ticker, weight) in enumerate(target.head(top_n).items(), start=1):
            score = float(alpha.get(ticker, 0.0)) if alpha is not None else 0.0
            lines.append(f"| {idx} | `{ticker}` | {weight * 100:.2f}% | {score:+.3f} | — |")
        lines.append("")
        lines.append(
            f"**Invested** {_pct(diagnostics.get('invested_weight'))} · "
            f"**cash** {_pct(diagnostics.get('cash_buffer'))} · "
            f"names held {diagnostics.get('target_names', 0)} · "
            f"median cost `{_fmt(diagnostics.get('median_cost_bps'))}` bps · "
            f"median KKT deadband `{_fmt(diagnostics.get('median_deadband_pct'))}` %"
        )
        lines.append("")
    else:
        lines.append("_No eligible portfolio could be constructed for this market in this run._")
        lines.append("")
    return lines


def _order_block(summary: dict[str, Any], top_n: int) -> list[str]:
    runs = summary.get("runs", [])
    tickets: list[dict[str, Any]] = []
    for run in runs:
        for ticket in getattr(run, "tickets", []) or []:
            tickets.append(ticket)
    lines = ["## Pending orders (await approval)", ""]
    if not tickets:
        lines.append(
            "✅ **No trades outside the no-trade deadband.** Every target weight is already inside its "
            "stock-specific KKT band `δ̂ = ĉ / (γ̂ σ̂²)`, so paying friction would destroy alpha."
        )
        lines.append("")
        return lines
    lines.append("| Market | Action | Ticker | Shares | Ref price | Target wt | Drift band | Cost (bps) | α z |")
    lines.append("| :--- | :---: | :--- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for ticket in tickets[: max(top_n * 3, 30)]:
        lines.append(
            f"| {ticket['market']} | **{ticket['action']}** | `{ticket['ticker']}` | {ticket['shares']:.0f} | "
            f"{ticket['ref_price']:,.2f} | {ticket['target_weight_pct']:.2f}% | ±{ticket['kkt_deadband_pct']:.2f}% | "
            f"{ticket['est_cost_bps']:.1f} | {ticket['alpha_z']:+.2f} |"
        )
    lines.append("")
    return lines


def _calibration_block(summary: dict[str, Any], config) -> list[str]:
    lines = ["## Self-calibrated parameters (this run)", ""]
    lines.append(
        f"- Kalman `Q̂,R̂`: learned per stock by innovation covariance matching "
        f"(Myers–Tapley), window `W = max({config.e('kalman.min_window', 10)}, ⌊√N × {config.e('kalman.window_sqrt_scale', 1.0)}⌋)`."
    )
    lines.append(
        f"- Event similarity gate `τ̂`: exact Student-t(383) null on S³⁸³ + Benjamini–Hochberg FDR "
        f"at `α = {config.e('events.fdr_alpha_scale', 1.0)}/√M`."
    )
    lines.append(
        f"- Event half-life `λ̂`: impulse-response MLE per domain, clipped to "
        f"[{config.e('events.half_life_min_days', 3.0)}, {config.e('events.half_life_max_days', 180.0)}] days."
    )
    lines.append(
        f"- Forensic gate mode `{config.e('forensics.gate_mode', 'quantile')}` "
        f"(statutory fallback: Beneish ≤ {config.e('forensics.statutory_beneish_gate', -1.78)}, "
        f"Piotroski ≥ {config.e('forensics.statutory_piotroski_gate', 6)})."
    )
    lines.append(
        f"- Transaction costs: Corwin–Schultz high-low spread + statutory friction "
        f"(INDIA STT/stamp duty/exchange/SEBI + 18% GST; US SEC §31 + FINRA TAF) + √-law impact."
    )
    lines.append(
        f"- Portfolio: True Ward-linkage HRP on a "
        f"{config.e('optimizer.cov_lookback_days', 160)}-day shrunk covariance, α tilt "
        f"{config.e('optimizer.alpha_tilt_strength', 0.35)}, cap {config.e('optimizer.max_weight', 0.06):.1%}, "
        f"turnover cap {config.e('optimizer.max_turnover', 0.35):.1%}."
    )
    lines.append("")
    return lines


def _approval_block() -> list[str]:
    return [
        "## Approval",
        "",
        "Comment one of the following on this issue:",
        "",
        "- `/approve` — book every pending order at its reference price plus estimated spread and statutory fees.",
        "- `/approve TICKER=shares@price ...` — book real broker fills, e.g. "
        "`/approve NVDA=25@128.40 RELIANCE.NS=40@2945.50`.",
        "",
        "The approval workflow reconciles splits/dividends, updates the event-sourced ledger, rebuilds the "
        "dashboard and closes this issue. Duplicate `/approve` comments are idempotent (the queue is cleared).",
        "",
    ]


def _lakehouse_block(summary: dict[str, Any]) -> list[str]:
    report = summary.get("lakehouse", {}) or {}
    lines = ["## Lakehouse integrity", ""]
    lines.append(f"- integrity: `{'OK' if report.get('ok') else 'FAILED'}`")
    for table, payload in (report.get("tables", {}) or {}).items():
        status = "ok" if not payload.get("issues") else "; ".join(payload["issues"])
        lines.append(f"- `{table}`: {payload.get('rows', 0):,} rows — {status}")
    ingested = summary.get("ingested", {}) or {}
    if ingested:
        lines.append("")
        lines.append("Shards merged this run: " + ", ".join(f"`{table}`={rows:,}" for table, rows in ingested.items()))
    lines.append("")
    lines.append(f"<sub>Generated {dt.datetime.now(dt.timezone.utc).isoformat()} · `src/main_v4.py`</sub>")
    return lines


def _fmt(value: Any) -> str:
    if value is None:
        return "n/a"
    try:
        number = float(value)
    except (TypeError, ValueError):
        return str(value)
    if not pd.notna(number):
        return "n/a"
    return f"{number:,.4f}"


def _pct(value: Any) -> str:
    try:
        return f"{float(value) * 100:.2f}%"
    except (TypeError, ValueError):
        return "n/a"


def load_pending_orders(state_dir: str | Path) -> list[dict[str, Any]]:
    orders: list[dict[str, Any]] = []
    for path in sorted(Path(state_dir).glob("pending_orders*.json")):
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue
        if isinstance(payload, dict):
            orders.extend(payload.get("orders", []) or [])
        elif isinstance(payload, list):
            orders.extend(payload)
    return orders
